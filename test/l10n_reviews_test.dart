import 'package:flutter_test/flutter_test.dart';

import 'package:beauty_salons/core/l10n/uz_strings.dart';

/// Тексты отзывов и портфолио мастера есть во всех четырёх словарях (латиница и кириллица, точные и шаблоны).
/// Проверяем наличие записей, а не отсутствие русских букв: tr() транслитерирует имена и выдаёт слова за узбекские.
void main() {
  const exact = <String>[
    'Выберите оценку от 1 до 5.',
    'Комментарий не длиннее 500 символов.',
    'Уберите из отзыва контакты и ссылки.',
    'Выберите причину или опишите, что не понравилось (от 10 символов).',
    'Отзыв можно оставить только после подтверждённого визита.',
    'Отзыв можно оставить в течение 7 дней после визита.',
    'Мастер не найден.',
    'Отзыв не найден.',
    'Править можно только свой отзыв.',
    'Отзыв можно изменить в течение 7 дней после визита.',
    'Отвечать можно только на отзывы о вас.',
    'Напишите ответ.',
    'Ответ не длиннее 500 символов.',
    'Уберите из ответа контакты и ссылки.',
    'Ответ мастера',
    'Подтверждённый визит',
    'Отзывов пока нет',
    'Показать ещё',
    'сегодня',
    'Только что',
    'изменён',
    'Отличный результат',
    'Аккуратная работа',
    'Пунктуальность',
    'Приятное общение',
    'Результат не устроил',
    'Неаккуратная работа',
    'Опоздание',
    'Грубое общение',
    'Чистота',
    'Уютная атмосфера',
    'Без ожидания',
    'Недостаточная чистота',
    'Шумно и неуютно',
    'Долгое ожидание',
  ];
  const templates = <String>[
    '{0} день назад',
    '{0} дня назад',
    '{0} дней назад',
    'Мастер: {0}',
    'Новый отзыв: {0} ★',
    'Автор: {0}',
  ];

  test('точные фразы есть в обоих узбекских словарях', () {
    for (final key in exact) {
      expect(uzExact[key], isNotNull, reason: 'нет в uzExact: $key');
      expect(uzCyrlExact[key], isNotNull, reason: 'нет в uzCyrlExact: $key');
      expect(uzExact[key], isNotEmpty);
      expect(uzCyrlExact[key], isNotEmpty);
    }
  });

  test('шаблоны есть в обоих узбекских словарях', () {
    for (final key in templates) {
      expect(uzTemplates[key], isNotNull, reason: 'нет в uzTemplates: $key');
      expect(uzCyrlTemplates[key], isNotNull, reason: 'нет в uzCyrlTemplates: $key');
    }
  });
}
